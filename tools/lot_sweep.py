"""Render a deterministic PlaceLot plan from the installed-data lot catalog.

Select every categorized ploppable lot, rather than the 1,734 growable/other
lots. The checked-in Lua table can be regenerated without game/code inputs.
"""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def plan(rows, size=256):
    margin, gap = (4, 1) if size == 128 else (8, 3)
    x = z = margin
    shelf = 0
    result = []
    order = (lambda r: (-int(r['depth']), -int(r['width']), int(r['iid'], 16))) if size == 128 else (lambda r: int(r['iid'], 16))
    selected = [r for r in rows if r['category'] != 'other']
    for row in sorted(selected, key=order):
        if row['category'] == 'other':
            continue
        width, depth = int(row['width']), int(row['depth'])
        if min(width, depth) <= 0 or max(width, depth) > size - 2 * margin:
            raise ValueError('lot does not fit: ' + row['iid'])
        if x + width > size - margin:
            x, z, shelf = margin, z + shelf + gap, 0
        if z + depth > size - margin:
            raise ValueError('catalog does not fit tile')
        result.append(dict(row, x=x, z=z))
        x += width + gap
        shelf = max(shelf, depth)
    return sorted(result, key=lambda r: int(r['iid'], 16))


def lua_string(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n').replace('\r', '\\r') + "'"


def render(rows, size=256):
    lots = plan(rows, size)
    lines = ['-- Generated by python tools/lot_sweep.py; game-data IIDs, cells, facing 0.', 'return {']
    for r in lots:
        lines.append('    {%s, %d, %d, %s, %s, %s, %s},' % (
            lua_string(r['iid'][2:]), r['x'], r['z'], r['width'], r['depth'],
            lua_string(r['category']), lua_string(r['name'])))
    return '\n'.join(lines + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', type=Path, default=ROOT / 'engine/tests/scenarios/lotconfigs.tsv')
    parser.add_argument('--size', type=int, default=256)
    args = parser.parse_args()
    with args.catalog.open(encoding='utf-8-sig', newline='') as stream:
        rows = list(csv.DictReader(stream, delimiter='\t'))
    try:
        print(render(rows, args.size), end='')
    except (ValueError, KeyError) as exc:
        parser.error(str(exc))


if __name__ == '__main__':
    main()
