// Independent authored input, not generated by the object's writer.
fn occupant_probe_fixture(empty: u8) -> Vec<u8> {
    let mut b = vec![
        3, 0, 4, 0, 2, 1, 0, 0xF4, 0x2B, 0xBD, 0x11, 0x6A, 0xFF, 0, 0, 0, 2, 0, 2, 0, 0, 0, 0, 0,
    ];
    b.extend_from_slice(&[0; 12]);
    b.extend_from_slice(&0x02F1_0010u32.to_le_bytes());
    b.extend_from_slice(&(-7i32).to_le_bytes());
    for v in [-24.5f32, 12.25, 40.0] {
        b.extend_from_slice(&v.to_le_bytes());
    }
    b.push(empty);
    b
}

unsafe extern "C" fn occupant_probe_sink(user: *mut c_void, bytes: *const u8, len: usize) {
    (*(user as *mut Vec<u8>)).extend_from_slice(std::slice::from_raw_parts(bytes, len));
}

#[test]
fn occupant_probe_authored_record_mutation_and_boolean_normalization() {
    for empty in [0, 1, 2] {
        let b = occupant_probe_fixture(empty);
        let mut r = fc4_landfill_occupant_probe_result::default();
        let mut output = Vec::<u8>::new();
        let p = [88.5f32, -4.0, 120.25];
        assert!(unsafe {
            fc4_landfill_occupant_probe(
                b.as_ptr(),
                b.len(),
                1,
                -123,
                p.as_ptr(),
                Some(occupant_probe_sink),
                &mut output as *mut _ as *mut c_void,
                &mut r,
            )
        });
        assert_eq!((r.read_ok, r.write_ok, r.qi_mask, r.ref_delta), (1, 1, 15, 1));
        assert_eq!(r.class_id, 0x8A22_BEBE);
        assert_eq!(r.previous_tile, 0x02F1_0010);
        assert_eq!(r.orientation, -123);
        assert_eq!(r.empty, u32::from(empty == 1));
        assert_eq!(r.bounds, [80.5, -4.0, 112.25, 96.5, 12.0, 128.25]);
        let mut expected = b;
        expected[7] &= 0xDD;
        expected[40..44].copy_from_slice(&(-123i32).to_le_bytes());
        for (i, v) in p.into_iter().enumerate() {
            expected[44 + i * 4..48 + i * 4].copy_from_slice(&v.to_le_bytes());
        }
        expected[56] = u8::from(empty == 1);
        assert_eq!(output, expected);
    }
}

#[test]
fn occupant_probe_version_boundaries_truncation_and_invalid_pointers() {
    for offset in [0, 2, 16, 18, 57] {
        let mut b = occupant_probe_fixture(0);
        if offset == 57 {
            b.pop();
        } else {
            b[offset] = 0;
        }
        let mut r = fc4_landfill_occupant_probe_result::default();
        assert!(unsafe {
            fc4_landfill_occupant_probe(
                b.as_ptr(),
                b.len(),
                0,
                0,
                std::ptr::null(),
                None,
                std::ptr::null_mut(),
                &mut r,
            )
        });
        // LG33: nested holder rejection leaves a good stream and the
        // landfill tail is read at that cursor, unlike outer/base rejection.
        let accepted = u32::from(offset == 16 || offset == 18);
        assert_eq!((r.read_ok, r.write_ok), (accepted, accepted));
        if accepted != 0 {
            let z_bits = if offset == 16 { 0x0010_0000 } else { 0x02F1_0010 };
            assert_eq!(r.position.map(f32::to_bits), [0, 0, z_bits]);
            assert_eq!(r.bounds, [-8.0, 0.0, -8.0, 8.0, 16.0, 8.0]);
        }
    }
    let mut r = fc4_landfill_occupant_probe_result::default();
    assert!(!unsafe {
        fc4_landfill_occupant_probe(
            std::ptr::null(),
            1,
            0,
            0,
            std::ptr::null(),
            None,
            std::ptr::null_mut(),
            &mut r,
        )
    });
    assert!(unsafe {
        fc4_landfill_occupant_probe(
            std::ptr::null(),
            0,
            0,
            0,
            std::ptr::null(),
            None,
            std::ptr::null_mut(),
            &mut r,
        )
    });
    assert_eq!((r.orientation, r.empty, r.flags, r.qi_mask), (0, 0, 4, 15));
}

#[derive(Default)]
struct Game {
    refs: RefCell<HashMap<u64, i32>>,
    agents: RefCell<Vec<(u32, String, u32)>>,
    subs: RefCell<Vec<u32>>,
    unsubs: Cell<u32>,
    services: Cell<i32>,
    removed_agent: Cell<u32>,
    supply: Cell<u32>,
    tile_cap: Cell<u32>,
    capacity: Cell<i32>,
    active: RefCell<BTreeMap<(i32, i32), bool>>,
    put: Cell<i64>,
    dept: Cell<u64>,
    current: Cell<i64>,
    full: RefCell<Vec<i64>>,
    places: Cell<u32>,
    slope: Cell<f32>,
    connected: Cell<bool>,
    props: RefCell<Vec<(u32, [f32; 3], i32)>>,
    next_prop: Cell<u64>,
    removed_props: RefCell<Vec<u64>>,
    history: RefCell<Vec<(u32, u32)>>,
    /// The developer whose tiles the game reports as its own occupants (the
    /// shadow tests: our handle plays the original).
    orig: Cell<usize>,
    /// Re-entrancy test: send_history delivers a zoning message to this
    /// handle once.
    reenter: Cell<usize>,
    /// Game tiles made through insert_landfill_tile: cell -> (tile,
    /// orientation, position, token).
    tiles: RefCell<BTreeMap<(i32, i32), GameTile>>,
    /// insert_landfill_tile answers 0.
    refuse_tiles: Cell<bool>,
}

/// A game tile: (tile, orientation, position, token).
type GameTile = (u32, i32, [f32; 3], u64);

fn game(u: *mut c_void) -> &'static Game {
    unsafe { &*(u as *const Game) }
}

impl Game {
    fn refs_of(&self, t: u64) -> i32 {
        self.refs.borrow().get(&t).copied().unwrap_or(0)
    }
    fn orig_tile(&self, x: i32, z: i32) -> Option<u32> {
        let p = self.orig.get() as *const fc4_landfill;
        if p.is_null() {
            return None;
        }
        let mut t = 0u32;
        unsafe { fc4_landfill_tile_at(p, x, z, &mut t, std::ptr::null_mut()) }.then_some(t)
    }
}

fn boxed(h: Option<fc4_core::property::PropertyHolder>) -> *mut fc4_props {
    h.map_or(std::ptr::null_mut(), |h| Box::into_raw(Box::new(h)) as *mut fc4_props)
}

