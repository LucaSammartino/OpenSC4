unsafe extern "C" fn put(u: *mut c_void, n: i32) {
    game(u).put.set(game(u).put.get() + i64::from(n));
}
unsafe extern "C" fn garbage_capacity(u: *mut c_void) -> i32 {
    game(u).capacity.get()
}
