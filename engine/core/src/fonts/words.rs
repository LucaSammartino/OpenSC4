/// SB, break-after (`0x00911FFE`): the set, or any control ≤ 0x20 except LF and CR.
pub fn is_break_after(c: u16) -> bool {
    in_ranges(c, SB) || (c <= 0x20 && c != 0x0A && c != 0x0D)
}

