// Game interfaces of the automata layer (docs/specs/automata.md), declared in
// the game's verified slot order (docs/abi/interfaces.tsv). Generated by
// build-runs/gen_automata_interfaces.py; edit the table there.
//
// Rule: these declarations contain NO overloads. MSVC lays out overloaded
// virtual functions in its own order (it groups them and reverses each group),
// so with overloads the slot order depends on the compiler rather than on the
// declaration. Every method here has a unique name and the vtable follows
// declaration order exactly: slot N is the N-th virtual function, counting
// QueryInterface, AddRef and Release as slots 0-2.
//
// Where the SDK lists a pair of overloads the names carry the arity
// (RemoveController1 / RemoveController2, Dispatch5 / Dispatch7,
// ChaseAutomaton2 / ChaseAutomaton4) and sit in the order the table gives.
// Two equal-arity pairs are assigned in the SDK's own order (glue19 question
// A2): TranslateDispatchLocationRect / ...Vec (slots 19, 20) and
// GetControllerOccName / ...OccTemplate (slots 18, 19).
